"""System-map picture, view 3: the notes repo among its neighbors.

Writes view3_topology.dot into the current directory: a literal Graphviz file with every
position pinned on the grid set below, so the .dot can also be edited by hand.
The content is drawn from drl-amr-notes/SYSTEM_MAP.md; when the map changes, change the
content lists here, update STAMP, and re-render. Usage:

    cd ~/projects/drl-amr-notes/presentations/system_map
    python ~/projects/drl-amr/tools/notes/system_map_view3.py
    neato -n2 -Tsvg view3_topology.dot -o view3_topology.svg
    neato -n2 -Tpng -Gdpi=150 view3_topology.dot -o view3_topology.png

The grammar and the method: ~/projects/system-builder/handoffs/
HANDOFF_2026-11-03_System_Map_Drawing_Method.md (and handoffs/used/ once retired).
"""

STAMP = "as of 2026-11-03 · drawn from SYSTEM_MAP.md"   # the snapshot date: change it on every redraw

IN = 72.0
H = 9.95

def P(x, yd): return f'"{x*IN:.1f},{(H-yd)*IN:.1f}!"'

EDITS  = 'style="rounded,filled", fillcolor="#eef5ff", color="#2b5ea8", penwidth=1.5'
CODE   = 'style="rounded,filled", fillcolor="#e9f6f3", color="#2a7d6f", penwidth=1.5'
RO     = 'style="filled", fillcolor="#f1f1f1", color="#777777", penwidth=1.5'
OUT    = 'style="filled", fillcolor="#ffffff", color="#999999", penwidth=1.0'
WALL   = 'shape=octagon, style="filled", fillcolor="#fdecea", color="#b03a2e", penwidth=2.4'
SUB    = 'style="rounded,filled", fillcolor="#ffffff", color="#2b5ea8", penwidth=1.0'

out = []; w = out.append
w('// View 3 — the notes repo among its neighbors.')
w('// Generated by system_map_view3.py (drl-amr tools/notes/); without it, edit by the grid below.')
w('// Rendered with:  neato -n2 -Tsvg view3_topology.dot -o view3_topology.svg')
w('// Every position is pinned (pos="x,y!" in points, y up).')
w('// Fill and border say who may write: blue = Claude edits (targeted, non-code); teal = code, which reaches disk only through Antone;')
w('// gray = read-only to Claude; white = outside the Mac; red octagon = a wall, drawn on the path it guards. Dotted line = a read; gray line = a propagation; teal line = carried by Antone.')
w('digraph topology {')
w('  graph [splines=false, outputorder=nodesfirst, bgcolor="white", pad=0.25];')
w('  node  [fontname="Helvetica", fontsize=11, shape=box, margin="0.10,0.05"];')
w('  edge  [arrowsize=0.75, penwidth=1.2, color="#666666", fontname="Helvetica"];')
w('')
w(f'  title [shape=plaintext, pos={P(9.1, 0.42)}, label=<<b><font point-size="19">drl-amr-notes among its neighbors</font></b><br/>'
  '<font point-size="11" color="#555555">what reads it, what feeds it, and what only Antone carries across</font><br/><font point-size="9" color="#888888">' + STAMP + '</font>>];')
w('')
w('  // ---- containers ----')
w(f'  mac [label="", style="rounded,filled", fillcolor="#fbfbfb", color="#555555", penwidth=1.2, width=12.5, height=7.45, fixedsize=true, pos={P(6.75, 4.95)}];')
w(f'  mac_lab [shape=plaintext, pos={P(2.75, 1.48)}, label=<<b>~/projects</b> on the Mac<br align="left"/><font point-size="9" color="#555555">Claude reads all of it; writes by targeted edit, never code</font><br align="left"/>>];')
w(f'  ext_lab [shape=plaintext, pos={P(16.55, 1.48)}, label=<<b>outside the Mac</b>>];')
w(f'  notes [label="", {EDITS}, width=5.7, height=3.5, fixedsize=true, pos={P(6.5, 4.75)}];')
w(f'  notes_lab [shape=plaintext, pos={P(5.55, 3.25)}, label=<<b>drl-amr-notes</b>  <font point-size="9" color="#555555">the documents · this map\'s subject</font>>];')
w('')
w('  // ---- inside the notes repo: the parts the neighbors touch ----')
for nid, x, y, t, d in [
    ("INDEX", 5.05, 4.1, "INDEX.md", "the hq report"),
    ("PROMPT", 7.95, 4.1, "claude_project/", "the system prompt (the only copy)"),
    ("SIDE", 5.05, 5.75, "SIDE_PROJECTS.md", "ideas parked with a revisit"),
    ("KNOW", 7.95, 5.75, "knowledge/", "explanations · SYMBOL_MAP"),
]:
    w(f'  {nid} [{SUB}, width=2.45, height=0.62, fixedsize=true, fontsize=10, pos={P(x, y)},'
      f' label=<<b>{t}</b><br/><font point-size="8.5" color="#555555">{d}</font>>];')
w('')
w('  // ---- neighbors on the Mac ----')
for nid, x, y, sty, t, d in [
    ("HQ", 2.3, 2.55, EDITS, "hq", "the chief of staff above the projects"),
    ("SB", 7.95, 2.25, EDITS, "system-builder", "the canonical operating agreement"),
    ("JX", 11.1, 4.75, CODE, "Jexpresso · JexpressoMeshes", "the solver; upstream smarras79"),
    ("JXO", 11.1, 6.45, RO, "~/projects/jx/", "run outputs · pinned source reads"),
    ("DRL", 6.5, 7.8, CODE, "drl-amr", "the agent (Python) · the notes tools"),
    ("SITE", 2.3, 7.8, CODE, "drl-amr-site", "the companion site (a side project)"),
]:
    w(f'  {nid} [{sty}, width=2.75, height=0.7, fixedsize=true, pos={P(x, y)},'
      f' label=<<b>{t}</b><br/><font point-size="8.5" color="#555555">{d}</font>>];')
w('')
w('  // ---- the wall: drl-amr D-072 (upstream-facing hygiene), on the path it guards ----')
w(f'  WALL [{WALL}, width=1.8, height=1.0, fixedsize=true, fontsize=9.5, pos={P(13.75, 4.75)},'
  ' label=<<b><font color="#b03a2e">WALL · D-072</font></b><br/><font point-size="8">upstream hygiene:<br/>self-contained text,<br/>through Antone only</font>>];')
w('')
w('  // ---- outside the Mac ----')
for nid, x, y, t, d in [
    ("CP", 16.55, 2.55, "Claude project", "prompt + project knowledge, as uploads"),
    ("UP", 16.55, 4.75, "smarras79/Jexpresso", "upstream, on GitHub"),
    ("BORAH", 16.55, 7.8, "Borah", "the HPC cluster (SLURM)"),
]:
    w(f'  {nid} [{OUT}, width=2.75, height=0.7, fixedsize=true, pos={P(x, y)},'
      f' label=<<b>{t}</b><br/><font point-size="8.5" color="#555555">{d}</font>>];')
w('')

def lab(nid, x, y, text, color="#555555"):
    w(f'  {nid} [shape=plaintext, fontsize=8.5, fontcolor="{color}", pos={P(x, y)}, label=<{text}>];')

w('  // ---- reads (dotted) ----')
w('  HQ -> INDEX [style=dotted, penwidth=1.5];')
w('  SITE -> notes [style=dotted, penwidth=1.5];')
w('')
w('  // ---- propagations (gray) ----')
w(f'  hq_down [shape=point, width=0.01, style=invis, pos={P(2.3, 5.75)}];')
w('  HQ -> hq_down [arrowhead=none];')
w('  hq_down -> SIDE;')
w('  SB -> PROMPT;')
w('  JX -> KNOW;')
w('  DRL -> notes;')
w('  JX -> JXO;')
w('')
w('  // ---- carried across by Antone (teal) ----')
w('  edge [color="#2a7d6f", penwidth=1.8];')
w('  PROMPT -> CP;')
w('  JX -> WALL;')
w('  WALL -> UP;')
w('  DRL -> BORAH;')
w('')
w('  // ---- arrow labels ----')
lab("l1", 3.0, 3.35, "reads the<br/>hq report")
lab("l2", 1.4, 4.55, "captures parked<br/>ideas: its one<br/>lane in")
lab("l3", 9.2, 2.83, "the agreement propagates<br/>into the prompt's §0")
lab("l4", 12.75, 3.6, "uploaded by Antone;<br/>git never feeds it", color="#2a7d6f")
lab("l5", 10.2, 5.52, "symbol map;<br/>every change<br/>explained")
lab("l6", 15.15, 4.5, "pull requests", color="#2a7d6f")
lab("l7", 11.85, 5.6, "runs and reads<br/>written here")
lab("l8", 7.45, 6.85, "the split tool<br/>works on the notes")
lab("l9", 3.15, 6.6, "reads the record's<br/>facts and words")
lab("l10", 13.3, 7.6, "cloned; training jobs", color="#2a7d6f")
w('')
w('  // ---- legend ----')
w(f'  leg_box [label="", style="rounded", color="#bbbbbb", width=17.95, height=0.95, fixedsize=true, pos={P(9.32, 9.38)}];')
items = [("Claude edits", "targeted, non-code", EDITS), ("code", "reaches disk through Antone", CODE),
         ("read-only to Claude", "", RO), ("outside the Mac", "", OUT), ("wall", "a rule every crossing obeys", WALL)]
for i, (t, d, sty) in enumerate(items):
    x = 1.55 + i * 2.35
    dd = f'<br/><font point-size="8" color="#555555">{d}</font>' if d else ""
    w(f'  lg{i} [{sty}, width=2.1, height=0.48, fixedsize=true, fontsize=9, pos={P(x, 9.38)}, label=<<b>{t}</b>{dd}>];')
lines = [("a read", 'style=dotted, penwidth=1.5, color="#666666"'), ("a propagation", 'penwidth=1.2, color="#666666"'),
         ("carried by Antone", 'penwidth=1.8, color="#2a7d6f"')]
for i, (t, sty) in enumerate(lines):
    x0 = 12.25 + i * 1.95
    w(f'  la{i} [shape=point, width=0.01, style=invis, pos={P(x0, 9.38)}];')
    w(f'  lb{i} [shape=point, width=0.01, style=invis, pos={P(x0+0.45, 9.38)}];')
    w(f'  la{i} -> lb{i} [{sty}];')
    w(f'  lt{i} [shape=plaintext, fontsize=9, pos={P(x0+1.15, 9.38)}, label="{t}"];')
w('}')
open("view3_topology.dot", "w").write("\n".join(out) + "\n")
