"""System-map picture, view 2: the session, with the operating agreement's boundary down the middle.

Writes view2_session.dot into the current directory: a literal Graphviz file with every
position pinned on the grid set below, so the .dot can also be edited by hand.
The content is drawn from drl-amr-notes/SYSTEM_MAP.md; when the map changes, change the
content lists here, update STAMP, and re-render. Usage:

    cd ~/projects/drl-amr-notes/presentations/system_map
    python ~/projects/drl-amr/tools/notes/system_map_view2.py
    neato -n2 -Tsvg view2_session.dot -o view2_session.svg
    neato -n2 -Tpng -Gdpi=150 view2_session.dot -o view2_session.png

The grammar and the method: ~/projects/system-builder/handoffs/
HANDOFF_2026-11-03_System_Map_Drawing_Method.md (and handoffs/used/ once retired).
"""

STAMP = "as of 2026-11-03 · drawn from SYSTEM_MAP.md"   # the snapshot date: change it on every redraw

IN = 72.0
STAGE_X = 1.42                  # stage-label column center
CX, NX, AX = 4.2, 8.1, 12.0   # Claude column, boundary, Antone column (centers)
BW, NW = 3.85, 2.75             # activity box width, crossing-note width
X0, X1 = 0.62, 14.2

CLAUDE = 'style="rounded,filled", fillcolor="#f3effa", color="#6a4fa0", penwidth=1.4'
ANTONE = 'style="rounded,filled", fillcolor="#e9f6f3", color="#2a7d6f", penwidth=1.4'
CROSS  = 'shape=note, style="filled", fillcolor="#ffffff", color="#444444", penwidth=1.2'

# (stage key, label, gloss, rows) ; row = (claude text, crossing text, direction, antone text, height)
#   direction: "r" Claude -> Antone, "l" Antone -> Claude
STAGES = [
  ("start", "START", "every session", [
    ("<b>Read INDEX.md</b>; orient: where, next, flags<br/>"
     "from a handoff: flag its carried threads<br/>"
     "state the agreement in three lines<br/>"
     "Implementation: recite the six-line protocol",
     "<b>the retire line</b>, when the<br/>session starts from a handoff", "r",
     "<b>Run the retire line</b><br/>answer questions in prose", 1.05)]),
  ("work", "WORK", "teach-and-build", [
    ("<b>Read</b> ~/projects through the connector<br/>"
     "draft and check in its own workspace<br/>"
     "explain before building (beat 1)<br/>"
     "<b>targeted edits</b> to documents, diff shown",
     "<b>code, one block at a time</b><br/>new files as downloads + mv", "r",
     "<b>Type</b> production code<br/><b>place</b> whole files with mv", 1.05),
    ("<b>Read the outputs back</b><br/>"
     "judge them against the pre-declared signals<br/>"
     "a missing signal is a finding, not a pass",
     "<b>run outputs</b><br/>written into ~/projects/jx/", "l",
     "<b>Run every command</b><br/>git · Julia · builds · tests<br/>Borah · renders", 1.0)]),
  ("wrap", "WRAP", "when the work warrants it", [
    ("<b>Roadmap tick</b> · beat 2 to the explanation doc<br/>"
     "<b>INDEX</b>: hq report, window entry in,<br/>the oldest entry out to its chronicle<br/>"
     "<b>decisions</b> to the log and its register",
     "<b>the handoff</b> (download + mv)<br/><b>git blocks</b>, one &amp;&amp; chain each,<br/>in the chat", "r",
     "<b>Place the handoff</b><br/><b>commit and push</b> both repos", 1.15)]),
  ("close", "PHASE CLOSE", "after a phase's last wrap", [
    ("<b>Close the chronicle</b> · trim the roadmap<br/>"
     "bank the recipes · check the log's volume<br/>"
     "audit every document's size<br/>"
     "<b>fresh-instance test</b> on the INDEX alone",
     "<b>banked files</b> as downloads + mv<br/><b>the split tool</b> when the log<br/>rolls over (dry run first)", "r",
     "<b>Place the banked files</b><br/>run the split tool --write<br/>commit", 1.15)]),
]

out = []; w = out.append
y = 1.45
rows_y = []   # (stage_key, y_center_of_row, row)
bands = []
for key, lab, gloss, rows in STAGES:
    top = y
    for row in rows:
        h = row[4]
        rows_y.append((key, y + h / 2 + 0.08, row))
        y += h + 0.08
    y += 0.12
    bands.append((key, lab, gloss, top, y))
    y += 0.14
FOOT_TOP = y + 0.05
H = FOOT_TOP + 1.05

def L(t): return t.replace('<br/>', '<br align="left"/>') + '<br align="left"/>'
def P(x, yd): return f'"{x*IN:.1f},{(H-yd)*IN:.1f}!"'

w('// View 2 — the session, with the operating agreement\'s boundary down the middle.')
w('// Generated by system_map_view2.py (drl-amr tools/notes/); without it, edit by the grid below.')
w('// Rendered with:  neato -n2 -Tsvg view2_session.dot -o view2_session.svg')
w('// Every position is pinned (pos="x,y!" in points, y up). Columns: Claude at '
  f'{CX*IN:.0f} pt, the boundary at {NX*IN:.0f} pt, Antone at {AX*IN:.0f} pt.')
w('// Boxes here are activities, not documents: violet = Claude\'s side, teal = Antone\'s side; folded notes are what crosses.')
w('digraph session {')
w('  graph [splines=false, outputorder=nodesfirst, bgcolor="white", pad=0.25];')
w('  node  [fontname="Helvetica", fontsize=10, shape=box, margin="0.12,0.06"];')
w('  edge  [arrowsize=0.75, penwidth=1.3, color="#444444"];')
w('')
w(f'  title [shape=plaintext, pos={P((X0+X1)/2, 0.4)}, label=<<b><font point-size="19">drl-amr — a session, and who does what</font></b><br/>'
  '<font point-size="11" color="#555555">the boundary is drawn by operation, not by tool: Claude reads and prepares, Antone runs, types and decides</font><br/><font point-size="9" color="#888888">' + STAMP + '</font>>];')
w('')
w('  // ---- stage bands ----')
for i, (key, lab, gloss, top, bot) in enumerate(bands):
    fill = "#f8f8f8" if i % 2 == 0 else "#ffffff"
    w(f'  band_{key} [label="", style="filled", fillcolor="{fill}", color="#dddddd", width={X1-X0-0.0:.2f},'
      f' height={bot-top:.2f}, fixedsize=true, pos={P((X0+X1)/2, (top+bot)/2)}];')
    w(f'  stage_{key} [shape=plaintext, fontsize=11, pos={P(STAGE_X, (top+bot)/2)}, label=<<table border="0" cellpadding="0" cellspacing="1">'
      f'<tr><td align="left" width="95"><b><font color="#333333">{lab}</font></b></td></tr>'
      f'<tr><td align="left" width="95"><font point-size="8.5" color="#666666">{gloss}</font></td></tr></table>>];')
w('')
w('  // ---- column heads ----')
w(f'  head_c [shape=plaintext, pos={P(CX, 1.15)}, label=<<b><font color="#6a4fa0">CLAUDE</font></b><font point-size="9" color="#555555">  reads ~/projects · edits documents · prepares</font>>];')
w(f'  head_x [shape=plaintext, pos={P(NX, 1.15)}, label=<<b><font color="#b03a2e">WHAT CROSSES</font></b>>];')
w(f'  head_a [shape=plaintext, pos={P(AX, 1.15)}, label=<<b><font color="#2a7d6f">ANTONE</font></b><font point-size="9" color="#555555">  runs every command · types code · decides</font>>];')
w('')
w('  // ---- the boundary (a zero-width dashed box, drawn behind the notes) ----')
w(f'  boundary [label="", shape=box, style="dashed", color="#b03a2e", penwidth=1.6, width=0.001, height={FOOT_TOP-1.35:.2f},'
  f' fixedsize=true, pos={P(NX, (1.35+FOOT_TOP)/2)}];')
w('')
w('  // ---- activities and crossings ----')
n = 0
for key, yc, (ctext, xtext, d, atext, h) in rows_y:
    n += 1
    w(f'  c{n} [{CLAUDE}, width={BW}, height={h-0.08:.2f}, fixedsize=true, pos={P(CX, yc)}, label=<{L(ctext)}>];')
    w(f'  x{n} [{CROSS}, width={NW}, height={min(h-0.2, 0.8):.2f}, fixedsize=true, pos={P(NX, yc)}, label=<{xtext}>];')
    w(f'  a{n} [{ANTONE}, width={BW}, height={h-0.08:.2f}, fixedsize=true, pos={P(AX, yc)}, label=<{L(atext)}>];')
    if d == "r":
        w(f'  c{n} -> x{n}; x{n} -> a{n};')
    else:
        w(f'  a{n} -> x{n}; x{n} -> c{n};')
w('')

# ---- the loop: next session (left gutter) ----
w('  // ---- the loop back to the next session, in the left gutter ----')
start_y = [r[1] for r in rows_y if r[0] == "start"][0]
wrap_y = [r[1] for r in rows_y if r[0] == "wrap"][0]
close_y = [r[1] for r in rows_y if r[0] == "close"][0]
GX = 0.3
w(f'  g_wrap  [shape=point, width=0.01, style=invis, pos={P(X0, wrap_y)}];')
w(f'  g_close [shape=point, width=0.01, style=invis, pos={P(X0, close_y)}];')
w(f'  g_wrap2 [shape=point, width=0.01, style=invis, pos={P(GX, wrap_y)}];')
w(f'  g_close2 [shape=point, width=0.01, style=invis, pos={P(GX, close_y)}];')
w(f'  g_top   [shape=point, width=0.01, style=invis, pos={P(GX, start_y)}];')
w(f'  g_start [shape=point, width=0.01, style=invis, pos={P(X0, start_y)}];')
w('  edge [color="#888888", penwidth=1.2];')
w('  g_close -> g_close2 [arrowhead=none]; g_close2 -> g_wrap2 [arrowhead=none];')
w('  g_wrap -> g_wrap2 [arrowhead=none]; g_wrap2 -> g_top [arrowhead=none]; g_top -> g_start;')
w(f'  loop_lab [shape=plaintext, fontsize=8.5, fontcolor="#777777", pos={P(GX+0.02, start_y-0.42)}, label=<next session>];')
w('')

# ---- footer: what never crosses ----
w('  // ---- footer ----')
w(f'  foot [shape=box, style="rounded", color="#b03a2e", penwidth=1.0, width={X1-X0:.2f}, height=0.78, fixedsize=true,'
  f' pos={P((X0+X1)/2, FOOT_TOP+0.45)}, fontsize=9.5, label=<'
  '<b><font color="#b03a2e">Never crosses.</font></b>  Claude never uses a shell on the Mac, never writes code to disk, never deletes a file,<br/>'
  'never overwrites a file whole, and does all the work itself (no subagents).  A general &quot;go ahead&quot; does not move the line;<br/>'
  'only a named, one-step exception does.  Questions are asked in prose.>];')
w('}')

open("view2_session.dot", "w").write("\n".join(out) + "\n")

